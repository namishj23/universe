// Who may call each mounted route, read from the guards themselves (`requireAuth` and the
// roles every `requireRole` carries), so docs/ROLES.md and the guard test can never drift
// from the code. Ownership checks inside handlers (your own records only) are not visible here.
import type { RequestHandler } from 'express';
import type { Role } from '@universe/contracts';
import type { MountedRouter } from '../app.js';
import { requireAuth } from './auth/guards.js';

export interface RouteGuard {
  method: string;
  /** OpenAPI-style path (`{id}`). */
  path: string;
  prefix: string;
  auth: boolean;
  /** Roles that pass every role check on the way; null when no check carries roles. */
  roles: Role[] | null;
}

interface Layer {
  handle: RequestHandler & { roles?: readonly Role[] };
  route?: { path: string; methods: Record<string, boolean>; stack: Layer[] };
}

/** The routes no session is needed for: signing in and the health checks. */
export const PUBLIC_ROUTES = [/^POST \/api\/auth\/login$/, /^GET \/api\/health\//];

export function routeTable(mounted: readonly MountedRouter[]): RouteGuard[] {
  const out: RouteGuard[] = [];
  for (const { prefix, router, guards = [] } of mounted) {
    const before: Layer['handle'][] = [...guards];
    for (const layer of (router as unknown as { stack: Layer[] }).stack) {
      if (!layer.route) {
        before.push(layer.handle); // router.use(...) applies to every route after it
        continue;
      }
      const chain = [...before, ...layer.route.stack.map((l) => l.handle)];
      const checks = chain.flatMap((h) => (h.roles ? [h.roles] : []));
      const roles =
        checks.length === 0
          ? null
          : checks.reduce<Role[]>((acc, r) => acc.filter((x) => r.includes(x)), [...checks[0]!]);
      const path = `${prefix}${layer.route.path === '/' ? '' : layer.route.path}`.replace(
        /:(\w+)/g,
        '{$1}',
      );
      for (const method of Object.keys(layer.route.methods))
        if (method !== '_all')
          out.push({
            method: method.toUpperCase(),
            path,
            prefix,
            auth: chain.includes(requireAuth),
            roles,
          });
    }
  }
  return out;
}

const ROLES: readonly Role[] = ['student', 'mentor', 'invigilator', 'driver', 'admin'];

/** `docs/ROLES.md`: modules and every route with the roles that may call it. */
export function rolesMarkdown(
  mounted: readonly MountedRouter[],
  modules: readonly { id: string; label: string; roles: readonly Role[] }[],
): string {
  const routes = routeTable(mounted);
  const tick = (roles: readonly Role[] | null) => ROLES.map((r) => (roles?.includes(r) ? '✓' : ''));
  const row = (cells: string[]) => `| ${cells.join(' | ')} |`;
  const head = [
    row(['Method', 'Path', 'Sign-in', ...ROLES]),
    row(Array<string>(3 + ROLES.length).fill('---')),
  ];
  const section = (title: string, list: RouteGuard[]) => [
    `### ${title}`,
    '',
    ...head,
    ...list.map((r) =>
      row([
        r.method,
        `\`${r.path}\``,
        r.auth ? 'required' : 'public',
        ...tick(r.auth ? r.roles : ROLES),
      ]),
    ),
    '',
  ];
  const byModule = new Map(modules.map((m) => [`/api/${m.id}`, m]));
  return [
    '# Roles and access',
    '',
    'Generated by `npm run docs:roles` from the guards on every mounted route: the platform’s `requireAuth`, the roles each `requireRole` carries (a module’s own roles are its outer guard) and `anyRole` for routes every signed-in role may call. Do not edit by hand: `npm test` fails when this file is stale, when a route has no sign-in guard (other than signing in and the health checks) and when a route has no role metadata.',
    '',
    'A ✓ means the role passes the route’s role checks. Inside the handler every route still checks ownership: other people’s records are 404, and some routes narrow further (hub mentor routes also need a mentor or peer-mentor profile; carpool offer routes need an approved carpool driver record; wellbeing returns only the caller’s own data and never admits admins).',
    '',
    '## Modules',
    '',
    row(['Module', 'Base path', ...ROLES]),
    row(Array<string>(2 + ROLES.length).fill('---')),
    ...modules.map((m) => row([m.label, `\`/api/${m.id}\``, ...tick(m.roles)])),
    '',
    '## Routes',
    '',
    ...section(
      'Platform',
      routes.filter((r) => !byModule.has(r.prefix)),
    ),
    ...[...byModule].flatMap(([prefix, m]) =>
      section(
        `${m.label} (\`${prefix}\`)`,
        routes.filter((r) => r.prefix === prefix),
      ),
    ),
  ].join('\n');
}
