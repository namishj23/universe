// Writes docs/sessions/U1-compare/README.md from the per-case results of `npm run design:compare`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../../docs/sessions/U1-compare/', import.meta.url);
const rows = readdirSync(new URL('results/', dir))
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(new URL(`results/${f}`, dir), 'utf8')));
const order = ['login', 'dashboard', 'inbox', 'admin-users', 'admin-audit'];
rows.sort(
  (a, b) => order.indexOf(a.screen) - order.indexOf(b.screen) || a.name.localeCompare(b.name),
);
const notes = readFileSync(new URL('NOTES.md', dir), 'utf8');
const table = rows
  .map(
    (r) =>
      `| ${r.screen} | ${r.role ?? '—'} | ${r.state} | ${r.theme} | ${r.viewport.width}×${r.viewport.height} | ${r.percent.toFixed(2)}% | [image](${r.name}.png) |`,
  )
  .join('\n');
const under = rows.filter((r) => r.viewport.width === 1440 && r.percent < 0.5).length;
const all1440 = rows.filter((r) => r.viewport.width === 1440).length;
writeFileSync(
  new URL('README.md', dir),
  `# U1 design comparison: prototype vs build\n\nGenerated by \`npm run design:compare\` (tools/design-compare). Each image is prototype | build | difference (red), at half size. Percent = differing pixels / all pixels, after masking request IDs, the prototype's demo note and its "viewing as" switcher (magenta).\n\n1440×900: ${under} of ${all1440} cases under 0.5%.\n\n${notes}\n\n| Screen | Role | State | Theme | Viewport | Difference | Side by side |\n| --- | --- | --- | --- | --- | --- | --- |\n${table}\n`,
);
console.log(`${rows.length} cases; 1440: ${under}/${all1440} under 0.5%`);
